"""Who is making this request, as FastAPI dependencies.

`get_current_user` and `get_current_admin` are what a route says instead of
checking a token itself; every plugin route generated by the registry gets the
result handed to it. Issuing and reading tokens lives here too, at module level
rather than inside the route, so that a sign-in can be exercised without HTTP.

The password rule and where a sign-in is written down are not decided here: the
application supplies both through KeepupSettings, because a rule the framework
invented would be a different rule from the one its invitations enforce.
"""

