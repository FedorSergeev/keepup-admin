def verify_password(plain_password: str, hashed_password: str):
    return bcrypt.checkpw(plain_password.encode('utf-8'), hashed_password.encode('utf-8'))


#: When the session this token belongs to began. Carried by the token rather
#: than kept on the server, which keeps no session state; renewal reads it to
#: know whether the session has gone on long enough.
SESSION_START_CLAIM = "sst"


def create_access_token(
        data: dict,
        expires_delta: Optional[timedelta] = None,
        session_started_at: Optional[datetime] = None,
):
    to_encode = data.copy()
    if expires_delta:
        expire = datetime.utcnow() + expires_delta
    else:
        expire = datetime.utcnow() + timedelta(minutes=15)
    to_encode.update({"exp": expire})

    # A renewal carries the beginning of the session forward unchanged. Stamping
    # "now" on every renewal is what made a session endless: each exchange would
    # reset the clock that is supposed to be running out.
    started = session_started_at or datetime.utcnow()
    to_encode.setdefault(SESSION_START_CLAIM, int(started.timestamp()))

    encoded_jwt = jwt.encode(to_encode, resolve_signing_key(), algorithm=ALGORITHM)
    return encoded_jwt


def issue_session_token(user_id: int, username: str, sid: Optional[str] = None,
                        session_started_at: Optional[datetime] = None) -> dict:
    """A token bound to a session record: a new session, or `sid` carried on.

    Every token the server hands a person or an agent goes through here, so every
    one of them can be revoked.
    """
    from keepup.auth.providers.base import ACCESS_TOKEN_EXPIRE_MINUTES
    lifetime = timedelta(minutes=ACCESS_TOKEN_EXPIRE_MINUTES)
    if sid is None:
        sid = panel_session.open_session(user_id, lifetime)
    else:
        panel_session.extend(sid, lifetime)
    token = create_access_token({"sub": username, panel_session.SESSION_CLAIM: sid},
                                expires_delta=lifetime, session_started_at=session_started_at)
    return {"access_token": token, "session_id": sid,
            "expires_in": int(lifetime.total_seconds())}


def _session_start(payload: dict) -> Optional[datetime]:
    """Read the session's beginning out of a decoded token, or None."""
    started = payload.get(SESSION_START_CLAIM)
    if started is None:
        return None
    try:
        return datetime.utcfromtimestamp(int(started))
    except (TypeError, ValueError, OSError):
        return None


async def request_token(request: Request, bearer: Optional[str] = Depends(oauth2_scheme)) -> Optional[str]:
    """The request's token: a real bearer header, else the panel session cookie."""
    return panel_session.token_from_request(request, bearer)


def _session_is_live(payload: dict) -> bool:
    """A token that names a session is good only while that session is.

    A token without one was issued before sessions were recorded and is accepted
    until it expires -- at most a day after the deployment.
    """
    sid = payload.get(panel_session.SESSION_CLAIM)
    if sid is None:
        return True
    try:
        return panel_session.is_active(sid)
    except Exception as error:
        # Failing open here would make revocation depend on the database being
        # up; failing closed only costs a retry.
        logger.error(f"Could not check session {str(sid)[:8]}...: {error}")
        return False


async def get_current_user(token: str = Depends(request_token)):
    """Return the current user of this token.

    The signature carries nothing but the token, and that is a rule rather than
    a detail: a scalar parameter with a default on a dependency is a *query*
    parameter to FastAPI. One used to stand here -- `ignore_empty_user` -- and
    it was published on every route of the framework and of every plugin, as a
    switch a caller could set to turn the check off. Code that wants None
    instead of a refusal calls get_optional_user() below, which is not a
    dependency and takes the token as an argument.

    One branch since task 170: the accounts live in this application's table.
    Somebody who signed in through an external provider is here too -- that
    path ends by issuing this same session, so by the time a request arrives
    there is nothing left to tell apart.
    """
    return await _get_local_user(token)


def _token_expiry(payload: dict) -> Optional[datetime]:
    """Read the expiry out of a decoded token payload, or None."""
    expires_at = payload.get("exp")
    if expires_at is None:
        return None
    try:
        return datetime.utcfromtimestamp(int(expires_at))
    except (TypeError, ValueError, OSError):
        return None


async def _get_local_user(token: Optional[str], ignore_empty_user: bool = False):
    credentials_exception = HTTPException(
        status_code=status.HTTP_401_UNAUTHORIZED,
        detail="Could not validate credentials",
        headers={"WWW-Authenticate": "Bearer"},
    )
    try:
        if token is None:
            if ignore_empty_user:
                return None
            raise credentials_exception
        payload = jwt.decode(token, resolve_signing_key(), algorithms=[ALGORITHM])
        username: str = payload.get("sub")
        if username is None:
            if ignore_empty_user:
                return None
            raise credentials_exception
        token_data = TokenData(username=username)
    except JWTError:
        if ignore_empty_user:
            return None
        raise credentials_exception

    if not _session_is_live(payload):
        raise credentials_exception

    user = get_user_by_username(token_data.username)
    if user is None:
        raise credentials_exception

    fresh_user = get_user_by_username(token_data.username)
    if fresh_user["status"] != "active":
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="User account is blocked",
        )

    # When this session ends. The server keeps no session state, so the moment
    # the token is decoded is the only place that knows -- and a handler that
    # needs to warn about the end (or record it alongside a websocket key)
    # cannot decode the token itself: it never sees it.
    fresh_user = dict(fresh_user)
    fresh_user["token_expires_at"] = _token_expiry(payload)
    fresh_user["session_started_at"] = _session_start(payload)
    fresh_user["session_id"] = payload.get(panel_session.SESSION_CLAIM)

    return fresh_user


async def get_optional_user(token: Optional[str]):
    """The user of this token, or None when there is none.

    For callers outside the request cycle -- a route that serves both a signed-in
    user and a guest, a socket that authenticates itself. Deliberately not a
    dependency: see get_current_user() for what happens when a switch like this
    ends up in a dependency's signature.

    Args:
        token: the bearer or panel token, or None.

    Returns:
        The user, or None when the token is absent, unreadable or names nobody.
    """
    return await _get_local_user(token, ignore_empty_user=True)


async def get_current_admin(current_user: dict = Depends(get_current_user)):
    if current_user["role"] != ROLE_ADMIN:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Admin access required",
        )
    return current_user


