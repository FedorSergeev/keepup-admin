def get_user_by_username(username: str):
    """Return a user by name, including the extra fields."""
    try:
        loop = asyncio.get_event_loop()
    except RuntimeError:
        loop = asyncio.new_event_loop()
        asyncio.set_event_loop(loop)

    if loop.is_running():
        import asyncio as async_module
        import threading

        result = None
        event = threading.Event()

        def run_in_thread():
            nonlocal result
            new_loop = async_module.new_event_loop()
            try:
                async_module.set_event_loop(new_loop)
                result = new_loop.run_until_complete(
                    auth_provider.get_user_info(username)
                )
            except Exception as e:
                logger.error(f"Error in thread: {e}")
            finally:
                # Closed on every path, including the failing one: a loop holds
                # an epoll descriptor and a self-pipe, and this runs once per
                # authenticated call. Left open, a long-lived process reaches its
                # descriptor limit and then cannot open anything at all -- which
                # surfaces as "database connection failed", not as a leak.
                try:
                    new_loop.close()
                except Exception as e:
                    logger.warning(f"Could not close the worker event loop: {e}")
                async_module.set_event_loop(None)
                event.set()

        thread = threading.Thread(target=run_in_thread)
        thread.start()
        thread.join(timeout=10)

        if event.is_set() and result is not None:
            return result
        else:
            logger.warning(f"Async call failed, falling back to DB for user {username}")
            return None

    user_info = loop.run_until_complete(
        auth_provider.get_user_info(username)
    )

    return user_info


def get_user_by_id(user_id: int):
    """Return a user by id, for any configured auth provider."""
    # TODO: auth_provider needs a lookup by id as well; without it this only
    # works against the local database.
    result = DatabaseManager.execute_query(
        "SELECT * FROM users WHERE id = ?",
        (user_id,),
        fetch_one=True
    )
    return result


def get_system_user_id():
    """Return the id of the system user that background work is signed with.

    The account itself is created once, at start-up, by
    `keepup.auth.seed_accounts` -- without a password anyone could sign in with.
    Creating it here as well is what let three spellings of it drift apart; a
    missing account now means the schema has not been initialised, and inventing
    one with a password of our own would only hide that.
    """
    try:
        system_user = get_user_by_username(seed_accounts.SYSTEM_USERNAME)
        if system_user:
            return system_user['id']
        logger.error(
            "The service account '%s' is not in the database: the schema was "
            "not initialised. Background work will go unsigned.",
            seed_accounts.SYSTEM_USERNAME)
        return None
    except Exception as e:
        logger.error(f"Error getting system user: {e}")
        return None


def get_all_users():
    """Return every user, for any configured auth provider."""
    return DatabaseManager.execute_query(
        "SELECT id, username, status, role, created_at FROM users ORDER BY created_at DESC"
    )


def save_user_to_db(username: str, password: str):
    """Create a user, for any configured auth provider."""
    password_hash = bcrypt.hashpw(password.encode('utf-8'), bcrypt.gensalt()).decode('utf-8')

    query = """
    INSERT INTO users (username, password_hash, status, role) 
    VALUES (?, ?, ?, ?)
    """

    if db_config.is_postgres():
        query += " RETURNING id"

    try:
        user_id = DatabaseManager.execute_commit(
            query,
            (username, password_hash, "blocked", ROLE_CLIENT)
        )
        return user_id

    except Exception as e:
        if "unique constraint" in str(e).lower() or "duplicate" in str(e).lower():
            raise HTTPException(status_code=400, detail="Username already exists")
        raise e


async def create_user(
        username: str,
        password: str,
        email: str = None,
        phone: str = None,
        full_name: str = None,
        agree_terms: bool = False
):
    user_id = auth_provider.create_user_in_db(username, password, email, phone, full_name, agree_terms)

    user_data = {"user_id": user_id, "username": (username,), "password": (password,), "email": email, "phone": phone,
                 "full_name": full_name, "agree_terms": agree_terms}

    await auth_provider.create_user(user_data)

    # The id is returned to the caller: it was computed and then thrown away,
    # while callers assigned the result to a variable and got None. The nearest
    # consequence was that creating test users considered itself unsuccessful
    # every time and never got as far as their wallets.
    return user_id


def update_user(user_id: int, status: Optional[str] = None, role: Optional[str] = None,
                email: Optional[str] = None, phone: Optional[str] = None, full_name: Optional[str] = None):
    """Update a user, including the extra fields."""
    conn = DatabaseManager.get_connection()
    cursor = conn.cursor()

    update_fields = []
    params = []

    if status is not None:
        update_fields.append("status = ?")
        params.append(status)

    if role is not None:
        update_fields.append("role = ?")
        params.append(role)

    if email is not None:
        update_fields.append("email = ?")
        params.append(email)

    if phone is not None:
        update_fields.append("phone = ?")
        params.append(phone)

    if full_name is not None:
        update_fields.append("full_name = ?")
        params.append(full_name)

    if not update_fields:
        return

    update_fields.append("updated_at = CURRENT_TIMESTAMP")
    params.append(user_id)

    query = f"UPDATE users SET {', '.join(update_fields)} WHERE id = ?"

    if db_config.is_postgres():
        query = query.replace('?', '%s')

    cursor.execute(query, params)
    conn.commit()
    cursor.close()
    conn.close()


